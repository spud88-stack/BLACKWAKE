export function mk(w, h) { const c = document.createElement('canvas'); c.width = w; c.height = h; return c; }
const cx = (c) => { const x = c.getContext('2d'); x.imageSmoothingEnabled = false; return x; };

export function shade(hex, f) {
  const n = parseInt(hex.slice(1), 16);
  let r = (n >> 16) & 255, g = (n >> 8) & 255, b = n & 255;
  if (f < 1) { r *= f; g *= f; b *= f; } else { r += (255 - r) * (f - 1); g += (255 - g) * (f - 1); b += (255 - b) * (f - 1); }
  return 'rgb(' + (r | 0) + ',' + (g | 0) + ',' + (b | 0) + ')';
}
const OUT = '#0a0b10';

function outline(c, col = OUT) {
  const w = c.width, h = c.height, src = cx(c).getImageData(0, 0, w, h), o = mk(w, h), x = cx(o);
  x.fillStyle = col;
  for (let y = 0; y < h; y++) for (let xx = 0; xx < w; xx++) {
    if (src.data[(y * w + xx) * 4 + 3] > 0) continue;
    const a = (dx, dy) => { const nx = xx + dx, ny = y + dy; return nx >= 0 && ny >= 0 && nx < w && ny < h && src.data[(ny * w + nx) * 4 + 3] > 0; };
    if (a(1, 0) || a(-1, 0) || a(0, 1) || a(0, -1)) x.fillRect(xx, y, 1, 1);
  }
  x.drawImage(c, 0, 0);
  return o;
}
function draw(w, h, fn, out) {
  const c = mk(w, h), x = cx(c);
  const R = (px, py, pw, ph, col) => { x.fillStyle = col; x.fillRect(px, py, pw, ph); };
  fn(R, x);
  return out ? outline(c) : c;
}

