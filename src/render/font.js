const GL = {};
for (const k in G) {
  const rows = G[k].split('|');
  GL[k] = { w: rows[0].length, rows: rows.map((r) => { const a = []; for (let i = 0; i < r.length; i++) if (r[i] === '#') a.push(i); return a; }) };
}

export function textWidth(s, scale = 1) {
  let w = 0;
  for (const ch of String(s).toUpperCase()) w += ((GL[ch] || GL['?']).w + 1) * scale;
  return Math.max(0, w - scale);
}

// align: 0 left, 0.5 centre, 1 right
export function text(ctx, s, x, y, col, o = {}) {
  s = String(s).toUpperCase();
  const scale = o.scale || 1;
  x = Math.round(x - textWidth(s, scale) * (o.align || 0));
  y = Math.round(y);
  const pass = (ox, oy, c) => {
    ctx.fillStyle = c;
    let cx = x + ox;
    for (const ch of s) {
      const g = GL[ch] || GL['?'];
      for (let r = 0; r < 5; r++) for (const px of g.rows[r]) ctx.fillRect(cx + px * scale, y + oy + r * scale, scale, scale);
      cx += (g.w + 1) * scale;
    }
  };
  if (o.shadow !== false) pass(scale, scale, o.shadowCol || 'rgba(0,0,0,0.75)');
  pass(0, 0, col || '#d8dde6');
  return textWidth(s, scale);
}

// Word-wrap to a pixel width. Returns lines.
export function wrap(s, maxW, scale = 1) {
  const words = String(s).split(' '), lines = [];
  let cur = '';
  for (const w of words) {
    const t = cur ? cur + ' ' + w : w;
    if (textWidth(t, scale) > maxW && cur) { lines.push(cur); cur = w; } else cur = t;
  }
  if (cur) lines.push(cur);
  return lines;
}
