// Soft radial glow in a single colour, dithered at the rim for a pixel look.
export function glowSprite(r, col, power = 2) {
  const c = mk(r * 2, r * 2), x = cx(c), id = x.createImageData(r * 2, r * 2);
  for (let y = 0; y < r * 2; y++) for (let xx = 0; xx < r * 2; xx++) {
    const d = Math.hypot(xx - r + 0.5, y - r + 0.5) / r;
    let a = d >= 1 ? 0 : Math.pow(1 - d, power);
    a = Math.floor(a * 8 + ((xx + y) % 2) * 0.5) / 8;
    const i = (y * r * 2 + xx) * 4;
    id.data[i] = col[0]; id.data[i + 1] = col[1]; id.data[i + 2] = col[2]; id.data[i + 3] = Math.min(255, a * 255);
  }
  x.putImageData(id, 0, 0);
  return c;
}

